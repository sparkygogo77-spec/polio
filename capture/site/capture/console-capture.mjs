#!/usr/bin/env node
/**
 * The snippet the owner pastes into his own browser's console, on his own
 * page with his own wallet connected, to capture it as it really is.
 *
 *   node capture/site/capture/console-capture.mjs [--seconds 60] > site/capture/console-capture.js
 *
 * The snippet is `sources-recorder.js` followed by the dump in `dump.mjs`,
 * the same one `capture-route.mjs` runs headless: it watches the page for
 * the given seconds (where each live value comes from, and how often it
 * refreshes), then dumps the page and downloads the capture as a file in
 * the same shape as `routes/<id>.json`, with its `sources` section. A
 * console has no accessibility tree to read, so the roles `capture-route.mjs`
 * writes are not in it.
 *
 * `console-capture.js`, beside this, is its output with the default 60
 * seconds, committed so it can be opened and copied without running Node.
 */
import { readFileSync } from "node:fs";
import { DUMP } from "./dump.mjs";

const args = process.argv.slice(2);
const i = args.indexOf("--seconds");
const seconds = i >= 0 ? Number(args[i + 1]) : 60;
if (!(seconds >= 0)) { console.error("--seconds takes a number, e.g. --seconds 60"); process.exit(2); }

const recorder = readFileSync(new URL("./sources-recorder.js", import.meta.url), "utf8");

process.stdout.write(`/*
 * SINK CONSOLE CAPTURE — generated by site/capture/console-capture.mjs; do not edit by hand.
 *
 * 1. Open the page on the live site, connect your wallet, and get it showing what you want captured.
 * 2. Open the console (F12, then Console). Chrome may ask you to type "allow pasting" first.
 * 3. Paste all of this and press Enter. Leave the tab open and in front for ${seconds} seconds,
 *    so a value that refreshes (the SOL price, a balance) is seen refreshing.
 * 4. The capture downloads as a .json file. Nothing is sent anywhere.
 *
 * What it keeps: the page's boxes, words and styles, and its data traffic (fetch, XHR, WebSocket:
 * addresses, how often each repeats, a small sample of each answer). What it never keeps: API
 * keys, tokens, auth headers, signatures, private keys or seed phrases; your wallet address in
 * any address or request is written {wallet}. It only sees traffic from the moment it is pasted:
 * a socket the page opened before that is not seen.
 */
${recorder.trim()}
;(async () => {
  const SECONDS = ${seconds};
  console.log("sink: watching the page for " + SECONDS + " seconds; leave this tab open…");
  await new Promise((r) => setTimeout(r, SECONDS * 1000));
  window.__sinkSources.mark();
  const cap = (${DUMP.toString()})();
  cap.sources = window.__sinkSources.report();
  cap.by = "console";
  const name = "capture-" + (location.pathname.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "") || "home") + ".json";
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([JSON.stringify(cap)], { type: "application/json" }));
  a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  console.log("sink: saved " + name + ": " + cap.sources.sources.length + " sources feeding " + cap.sources.feeds.length + " elements.");
})();
`);
