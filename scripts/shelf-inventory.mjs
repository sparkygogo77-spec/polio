/**
 * Writes docs/shelf-inventory.md from the data the shelf itself reads:
 * every category, group and item, what each does, what a published page
 * does with it, and where it came from. Run after changing the shelf plan.
 *
 *   node scripts/shelf-inventory.mjs
 */
import { writeFileSync } from "node:fs";
import { CATEGORIES, FEATURES } from "../src/features/studio/shelf/catalog.ts";
import { SHELF_GROUPS, isWorkKey, workIdOf } from "../src/features/studio/shelf/shelfGroups.ts";
import { REMOVED, VARIANTS, publishOf } from "../src/features/studio/shelf/shelfPlan.ts";
import { STATUS_LABEL, doesOf, needsOf, statusOf, switchOf, NEED_LABEL } from "../src/features/studio/shelfFacts.ts";
import { LIBRARY } from "../src/features/studio/shelf/library/works.ts";

const byId = new Map(FEATURES.map((f) => [f.id, f]));
const work = (k) => LIBRARY.find((w) => w.manifest.id === workIdOf(k));
const name = (k) => (isWorkKey(k) ? work(k)?.manifest.name : byId.get(k)?.name) ?? k;
const does = (k) => (isWorkKey(k) ? work(k)?.manifest.blurb : doesOf(byId.get(k))) ?? "";
const status = (k) => (isWorkKey(k) ? statusOf(k, work(k)?.manifest.needs) : statusOf(k));
const origin = (k) => (isWorkKey(k) ? "library feature (built in); a capture's own version joins it" : "built-in catalogue");
const published = (k) => {
  const p = publishOf(k);
  if (p.kind === "draws") return "drawn complete";
  if (p.kind === "runs") return { "site-motion": "runs: assets/site-motion.js", parts: "runs: assets/parts.js", keyframes: "runs: keyframes in site.css", "view-transition": "runs: the browser's fade between pages", work: "runs: its feature script" }[p.by];
  if (p.kind === "still") return `still until built (waits on ${p.waits})`;
  if (p.kind === "brief") return "written into the brief";
  return "never published (for the builder)";
};
const needs = (k) => (isWorkKey(k) ? (work(k)?.manifest.needs !== "none" ? [work(k)?.manifest.needs] : []) : needsOf({ id: k }).map((n) => NEED_LABEL[n].toLowerCase()));
/*
 * Before Lane I: what the card said (the old rule: a picture-only stand-in,
 * a motion the preview only named, or anything needing a key or backend was
 * "Idea, needs building"; everything else "Works now"), and whether the
 * published page bore it out. Only drawn parts and library features did:
 * no script shipped for the whole-site motions or the parts that answer a
 * press, and a note for the builder was published as a dashed box.
 */
const PICTURE_ONLY = new Set(["checkout", "subscription", "invoice", "moderation", "ai-chat", "ai-prompt-box", "ai-generate-content", "ai-summarize", "ai-translate", "ai-recommend", "ai-moderation", "ai-voice", "auth", "cookie-consent", "i18n", "theming", "dark-mode", "qr-bridge", "weather-time", "print", "seo", "analytics", "database", "api", "pwa", "perf", "testing", "email", "cms", "versioning", "integration", "captcha"]);
const NAMED = new Set(["sticky-story", "scroll-video", "morph-transition", "physics", "horizontal-scroll", "infinite-scroll"]);
const before = (k) => {
  if (isWorkKey(k)) return "Works now; true";
  const idea = PICTURE_ONLY.has(k) || NAMED.has(k) || needsOf({ id: k }).length;
  if (idea) return "Idea; true";
  const p = publishOf(k);
  const was = p.kind === "draws" ? "true" : p.kind === "note" ? "no: published as a dashed note" : "no: published still";
  return `Works now; ${was}`;
};
const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\n/g, " ");

const out = [];
const cards = Object.values(SHELF_GROUPS).flatMap((gs) => gs.flatMap((g) => g.items));
const versions = Object.values(VARIANTS).flatMap((v) => v.more);
out.push(`# The parts shelf, item by item

Generated by \`node scripts/shelf-inventory.mjs\` from the data the shelf reads
(\`shelfGroups.ts\`, \`shelfPlan.ts\`, \`shelfFacts.ts\`, \`library/works.ts\`), so it
cannot drift from what a person sees. Lane I.

**Counts.** Before: ${CATEGORIES.length} categories, ${FEATURES.length} catalogue cards plus ${LIBRARY.length} library
feature cards in a separate band (${FEATURES.length + LIBRARY.length}). After: ${CATEGORIES.length} categories and ${cards.length} cards;
${versions.length} near-copies are versions of a card; ${Object.keys(REMOVED).length} were taken off the shelf. Every id
still draws where a saved page has one.

**Badges** say what the published page does, which is plain HTML with no React:
*${STATUS_LABEL.works}* (drawn complete, or its script ships), *${STATUS_LABEL.build}* (shown
still until a build makes it real), *${STATUS_LABEL.service}* (waits on an outside service
or a server), *${STATUS_LABEL.note}* (words in the blueprint, never on the page).
\`tests/shelf-publish.mjs\` exports every item that says it works and checks it does.

**Where things come from.** *Built-in catalogue* is \`catalog.ts\`. *Library feature*
is working code in \`library/\` that goes onto a part. *Captured* effects are not
cards of their own: when a capture brings one (sink's \`doc.behaviours\`, or the
page's own \`:hover\` and keyframe loops), it appears on the card that does the
same effect, as the version "As on <site>" (\`library/siteVersions.ts\`).

**New idea** is the dashed button at the end of the categories: it drops a New
idea part where you are looking. The notes for the builder live under Text.
`);

for (const c of CATEGORIES) {
  out.push(`\n## ${c.label}\n\n${c.blurb}\n`);
  for (const g of SHELF_GROUPS[c.id] ?? []) {
    out.push(`\n### ${g.label}\n\n| Item | What it does | When published | Badge | Before: said; true? | Needs | Versions | From |\n|---|---|---|---|---|---|---|---|`);
    for (const k of g.items) {
      const v = VARIANTS[k];
      const vs = v ? [v.self, ...v.more.map((m) => `${m.label} (${isWorkKey(m.key) ? "feature" : m.key}, ${STATUS_LABEL[status(m.key)].toLowerCase()})`)].join("; ") : "";
      const sw = !isWorkKey(k) && switchOf(k) ? " Whole-site switch." : "";
      out.push(`| ${cell(name(k))} \`${k}\` | ${cell(does(k))}${sw} | ${cell(published(k))} | ${STATUS_LABEL[status(k)]} | ${cell(before(k))} | ${cell(needs(k).join(", ") || "nothing")} | ${cell(vs)} | ${origin(k)} |`);
    }
  }
}

out.push(`\n## Taken off the shelf\n\n| Id | Was | Why, and where it lives now |\n|---|---|---|`);
for (const [id, why] of Object.entries(REMOVED)) out.push(`| \`${id}\` | ${cell(byId.get(id)?.name)} | ${cell(why)} |`);

out.push(`\n## Merged: near-copies that are versions now\n\n| Was a card | Is now a version of |\n|---|---|`);
for (const [item, v] of Object.entries(VARIANTS)) for (const m of v.more) out.push(`| ${cell(name(m.key))} \`${m.key}\` | ${cell(name(item))} \`${item}\` |`);

out.push(`\n## What a capture brings, and where it lands

| Sink records | Attached as | Shelf card it is a version of |
|---|---|---|
| \`reveal[]\`, \`intro[]\` | Reveal on scroll | Appear on scroll |
| \`loops[]\` marquee, \`scrollSpeed[]\` | Marquee loop | Scrolling ticker |
| \`pointer[]\` move | Follow the pointer | Depth scrolling |
| \`scrollClass[]\` | Header bar on scroll | Sticky top bar |
| \`loader\` | CRT loader | Opening animation |
| \`idle[]\` that goes dark | Blink | Blink |
| \`motion.spin[]\`, a keyframe loop that turns | Spin | Spin |
| \`motion.float[]\`, a keyframe loop that travels | Float | Float |
| \`motion.hover[]\` tilt (script) | Tilt | Tilt on hover |
| \`motion.hover[]\` lift (script), a stylesheet \`:hover\` that moves | Lift on hover | Lift on hover |
| \`motion.scrollGrow[]\` | Grow with the scroll | Scroll progress bar |
| \`motion.canvases[]\` particles | Dust | Dust |
| \`states[]\` (presses) | Show on press | Tabs |
| \`worlds[]\` | Characters open their dialogs | Characters open their dialogs |
| \`node.embed\` | the page inside a part | Embed |

Recorded but attaching nothing yet, so not on the shelf: a pointer that turns a
part (\`pointer[]\` turn), a drifting loop (\`loops[]\` drift), idle loops that do
not go dark, canvases that repaint or stand still, \`heldVisible[]\`.
`);

writeFileSync("docs/shelf-inventory.md", out.join("\n") + "\n");
console.log(`docs/shelf-inventory.md: ${cards.length} cards, ${versions.length} versions, ${Object.keys(REMOVED).length} taken off`);
