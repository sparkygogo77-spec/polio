/**
 * What has landed: read out of the history, and readable in a minute.
 *
 * The two rules the panel exists to keep, checked rather than hoped for:
 *
 *   · every line came from git — the generator is the only author, and no
 *     hand-written changelog file feeds it;
 *   · it leads with features, groups by pass, newest first, one line each,
 *     and the specifics stay folded until asked for;
 *   · and it opens from the bar, closes on Escape and on a press outside.
 *
 *   node tests/updates.mjs [url]     # default http://localhost:3000
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { GENERATED_AT, KIND_MEANS, PASSES, leadOf, minutes, onlyUsable, sizeOf } from "../src/features/studio/passes.ts";

const results = [];
const check = (name, ok, detail = "") => {
  results.push(ok);
  console.log(`${ok ? "  ok  " : " FAIL "} ${name}${detail ? ` — ${detail}` : ""}`);
};

/* ------------------------------------------------------------------ */
/* 1. It is real history                                               */
/* ------------------------------------------------------------------ */

check("there are passes at all", PASSES.length > 0, `${PASSES.length}`);
check("the file says when it was read", /^\d{4}-\d{2}-\d{2}T/.test(GENERATED_AT), GENERATED_AT);

const shas = PASSES.flatMap((p) => p.changes.map((c) => c.id));
check("every line carries the sha it came from", shas.every((s) => /^[0-9a-f]{7,40}$/.test(s)), `${shas.length} lines`);

const known = new Set(
  execFileSync("git", ["log", "--format=%h", "-400"], { encoding: "utf8" }).split("\n").map((s) => s.trim()).filter(Boolean),
);
const strangers = shas.filter((s) => !known.has(s));
check("no line was invented: each sha is a commit in this repo", strangers.length === 0, strangers.slice(0, 3).join(" "));

const subjects = new Map(
  execFileSync("git", ["log", "--format=%h~;~%s", "-400"], { encoding: "utf8" })
    .split("\n").filter(Boolean).map((r) => r.split("~;~")),
);
const wrong = PASSES.flatMap((p) => p.changes).filter((c) => subjects.get(c.id) !== c.says);
check("every line is the commit's own words, not a rewrite", wrong.length === 0, wrong.slice(0, 2).map((c) => c.id).join(" "));

check("no merge subject leaked in as a feature",
  PASSES.every((p) => p.changes.every((c) => !c.says.startsWith("Merge "))));

/* ------------------------------------------------------------------ */
/* 2. The dead chore stays dead                                        */
/* ------------------------------------------------------------------ */

const gen = readFileSync("src/features/studio/passes.generated.ts", "utf8");
check("the generated file says it is generated and not to be edited",
  /Generated by/.test(gen) && /Do not edit by hand/.test(gen));

const script = readFileSync("scripts/passes.mjs", "utf8");
check("the generator's only source is git", /execFileSync\("git"/.test(script));
check("nothing reads a hand-written changelog file",
  !/CHANGELOG[.\w]*["'`]/i.test(script) && !/readFileSync|import .*CHANGELOG/i.test(readFileSync("src/features/studio/Updates.tsx", "utf8")));

let hasChangelog = true;
try { readFileSync("CHANGELOG.md"); } catch { hasChangelog = false; }
check("there is no changelog file to keep", !hasChangelog);

/* ------------------------------------------------------------------ */
/* 3. Newest first, grouped by pass                                    */
/* ------------------------------------------------------------------ */

const times = PASSES.map((p) => Date.parse(p.when));
check("passes run newest first", times.every((t, i) => i === 0 || t <= times[i - 1]));
check("every pass carries at least one change", PASSES.every((p) => p.changes.length > 0));
check("a pass says the day it landed", PASSES.every((p) => /^\d{1,2} [A-Z][a-z]+$/.test(p.day)), PASSES[0].day);
check("no pass is a wall: twelve lines at most, the rest counted",
  PASSES.every((p) => p.changes.length <= 12 && p.more >= 0));

const ids = PASSES.flatMap((p) => p.changes.map((c) => c.says));
check("nothing is told twice across passes", new Set(ids).size === ids.length, `${ids.length} lines, ${new Set(ids).size} distinct`);

/* ------------------------------------------------------------------ */
/* 4. Features first                                                   */
/* ------------------------------------------------------------------ */

for (const p of PASSES.slice(0, 6)) {
  const lead = leadOf(p);
  const kinds = new Set(p.changes.map((c) => c.kind));
  const best = ["new", "better", "fixed", "under"].find((k) => kinds.has(k));
  check(`${p.id} leads with the strongest thing in it`, lead && lead.kind === best, `${lead?.kind} of ${[...kinds].join("/")}`);
}
check("every kind has a word a person reads", Object.values(KIND_MEANS).every((w) => w.length > 1));
check("a pass says its size in words rather than a bare count", /[a-z]/.test(sizeOf(PASSES[0])), sizeOf(PASSES[0]));

const usable = onlyUsable(PASSES);
check("the plumbing can be dropped and features remain", usable.length > 0 && usable.length <= PASSES.length,
  `${usable.length} of ${PASSES.length}`);
check("dropping the plumbing drops only plumbing",
  usable.every((p) => p.changes.every((c) => c.kind !== "under")));

/* ------------------------------------------------------------------ */
/* 5. A minute to read                                                 */
/* ------------------------------------------------------------------ */

const read = minutes(PASSES);
check("the whole thing reads in about a minute", read >= 1 && read <= 3, `${read} min`);
check("the specifics are short enough to unfold",
  PASSES.every((p) => p.changes.every((c) => c.detail.length <= 6)));

/* ------------------------------------------------------------------ */
/* 6. The panel itself                                                 */
/* ------------------------------------------------------------------ */

const panel = readFileSync("src/features/studio/Updates.tsx", "utf8");
check("it borrows the timeline's cards rather than inventing a second way",
  /from "\.\/TimelineDetail"/.test(panel) && /\bRow\b/.test(panel) && /\bFIELD\b/.test(panel));
check("it is a slide over standing on nearly the whole screen",
  /fixed/.test(panel) && /w-\[calc\(100vw-1\.5rem\)\]/.test(panel) && /100dvh/.test(panel));
check("the lines stay in a column a person can read", /max-w-\[1100px\]/.test(panel));
check("Escape and a press outside close it", /D\.Root/.test(panel) && /D\.Overlay/.test(panel));
check("the specifics start folded", /React\.useState\(false\)/.test(panel));

const bar = readFileSync("src/features/studio/StudioPage.tsx", "utf8");
check("one control was added to the bar, no more",
  (bar.match(/UpdatesToggle/g) || []).length === 2 && (bar.match(/UpdatesPanel/g) || []).length === 2);
check("the addition says the bar belongs to the sibling", /belongs to the sibling/.test(bar));

/* ------------------------------------------------------------------ */
/* 7. In the browser                                                   */
/* ------------------------------------------------------------------ */

const url = process.argv[2] || "http://localhost:3000";
let live = false;
try {
  const res = await fetch(`${url}/builder`, { signal: AbortSignal.timeout(8000) });
  live = res.ok;
} catch { live = false; }
check("the Builder answers", live, live ? url : `${url} — skipped the live half`);

const passed = results.filter(Boolean).length;
console.log(`\n${passed}/${results.length} passed`);
process.exit(passed === results.length ? 0 : 1);
